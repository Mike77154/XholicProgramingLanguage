static char *read_all(const char *path, size_t *out_len){
  FILE *f=fopen(path,"rb"); if(!f){perror("open"); exit(1);}
  if(fseek(f,0,SEEK_END)!=0){perror("fseek"); exit(1);}
  long nl=ftell(f); if(nl<0){perror("ftell"); exit(1);} size_t n=(size_t)nl;
  if(fseek(f,0,SEEK_SET)!=0){perror("fseek"); exit(1);}
  char *buf=(char*)malloc(n+1); if(!buf){fprintf(stderr,"oom\n"); exit(1);}
  size_t rd=fread(buf,1,n,f); fclose(f); if(rd!=n){fprintf(stderr,"short read (%zu/%zu)\n", rd, n); exit(1);}
  buf[n]=0; if(out_len)*out_len=n; return buf;
}

/* ---------- String builder ---------- */
typedef struct { char *buf; size_t n, cap; } Str;
static void sb_init(Str*s){ s->cap=1<<14; s->n=0; s->buf=(char*)malloc(s->cap); s->buf[0]=0; }
static void sb_reserve(Str*s,size_t need){ if(s->n+need+1>s->cap){ s->cap=(s->n+need+1)*2; s->buf=(char*)realloc(s->buf,s->cap);} }
static void sb_puts(Str*s,const char*x){ size_t m=strlen(x); sb_reserve(s,m); memcpy(s->buf+s->n,x,m); s->n+=m; s->buf[s->n]=0; }
static void sb_printf(Str*s,const char*fmt,...){ char tmp[16384]; va_list ap; va_start(ap,fmt); int m=vsnprintf(tmp,sizeof(tmp),fmt,ap); va_end(ap); if(m>0){ sb_reserve(s,(size_t)m); memcpy(s->buf+s->n,tmp,(size_t)m); s->n+=m; s->buf[s->n]=0; }}

/* ---------- Lexer ---------- */
typedef enum {
  T_EOF=0, T_ID, T_NUM, T_STR, T_CHAR, T_NEWLINE, T_COLON, T_COMMA, T_SEMI,
  T_LP, T_RP, T_DOT, T_EQSIGN,
  /* keywords */
  K_U0, K_DEFFUNK, K_DEFUNC, K_END, K_RETURN, K_EXTERN,
  /* control */
  K_IF, K_ELIF, K_ELSE, K_WHILE, K_FOR,
  /* word-operators */
  K_GT, K_LT, K_GE, K_LE, K_EQ, K_NE, K_AND, K_OR, K_NOT,
  /* new control words */
  K_BREAK, K_CONTINUE,
  /* INI */
  K_INI_SEC
} Tok;

typedef struct { Tok kind; char *lex; U64 u64; F64 f64; int line,col; } Token;
static Src S; static Token tk;

static int is_ident1(int c){ return isalpha(c)||c=='_'||c=='$'||c=='@'; }
static int is_ident(int c){ return isalnum(c)||c=='_'||c=='$'||c=='@'; }
static char peek(){ return (S.pos<S.len)? S.data[S.pos] : 0; }
static char getc1(){ if(S.pos>=S.len) return 0; char c=S.data[S.pos++]; if(c=='\n'){S.line++;S.col=1;} else S.col++; return c; }
static void skip_ws(){
  for(;;){
    if(S.pos>=S.len) return;
    char c=S.data[S.pos];
    if(c==' '||c=='\t'||c=='\r'){ S.pos++; S.col++; continue; }
    if(c==';'||c=='#'||(c=='/' && S.pos+1<S.len && S.data[S.pos+1]=='/')){
      while(S.pos<S.len && S.data[S.pos]!='\n') S.pos++;
      continue;
    }
    break;
  }
}
static Token make(Tok k,const char*lex,int l,int c){ Token t={k, lex?strdup(lex):NULL,0,0.0,l,c}; return t; }

static int is_hex(char c){ return (c>='0'&&c<='9')||(c>='a'&&c<='f')||(c>='A'&&c<='F'); }
static int hex_val(char c){ if(c>='0'&&c<='9') return c-'0'; if(c>='a'&&c<='f') return 10+c-'a'; if(c>='A'&&c<='F') return 10+c-'A'; return 0; }

static Token next(){
  skip_ws(); int l=S.line, c=S.col;
  if(S.pos>=S.len) return make(T_EOF,NULL,l,c);
  char ch=getc1();
  if(ch=='\n') return make(T_NEWLINE,NULL,l,c);
  if(ch==':')  return make(T_COLON,":",l,c);
  if(ch==',')  return make(T_COMMA,",",l,c);
  if(ch==';')  return make(T_SEMI,";",l,c);
  if(ch=='(')  return make(T_LP,"(",l,c);
  if(ch==')')  return make(T_RP,")",l,c);
  if(ch=='.')  return make(T_DOT,".",l,c);
  if(ch=='=')  return make(T_EQSIGN,"=",l,c);

  if(ch=='"'){ /* string or "" fmt or "c" for extern "c" */
    if(peek()=='"'){ getc1(); return make(T_STR,"%%FORMAT_FROM_VAR%%",l,c); }
    char buf[1<<14]; int n=0;
    while(S.pos<S.len){
      char d=getc1(); if(d=='"') break;
      if(d=='\\' && S.pos<S.len){
        char e=getc1();
        if(e=='n') buf[n++]='\n';
        else if(e=='t') buf[n++]='\t';
        else if(e=='x'){ /* \xNN */
          int hi = is_hex(peek())? hex_val(getc1()):0;
          int lo = is_hex(peek())? hex_val(getc1()):0;
          buf[n++] = (char)((hi<<4)|lo);
        } else if(e=='"' || e=='\\'){ buf[n++]=e; }
        else { buf[n++]=e; }
      } else buf[n++]=d;
      if(n>=((int)sizeof(buf))-1) break;
    }
    buf[n]=0; return make(T_STR,buf,l,c);
  }
  if(ch=='\''){ /* char or '' expr */
    if(peek()=='\''){ getc1(); return make(T_CHAR,"%%PUTCHAR_EXPR%%",l,c); }
    char v=getc1();
    if(v=='\\'){ char e=getc1(); if(e=='n') v='\n'; else if(e=='t') v='\t'; else if(e=='\''||e=='\\') v=e; }
    if(getc1()!='\''){ fprintf(stderr,"%s:%d:%d: char literal error\n", g_input_name, l, c); }
    char *lex=(char*)malloc(8); lex[0]=v; lex[1]=0; return make(T_CHAR,lex,l,c);
  }
  if(isdigit(ch)){
    /* bases y exponentes */
    char buf[256]; int n=0; buf[n++]=ch;
    if(ch=='0' && (peek()=='x'||peek()=='X'||peek()=='b'||peek()=='B'||peek()=='o'||peek()=='O')){
      char b=getc1(); buf[n++]=b;
      if(b=='x'||b=='X'){ while(is_hex(peek()) && n<255) buf[n++]=getc1(); }
      else if(b=='b'||b=='B'){ while((peek()=='0'||peek()=='1') && n<255) buf[n++]=getc1(); }
      else { while((peek()>='0'&&peek()<='7') && n<255) buf[n++]=getc1(); }
      buf[n]=0; Token t=make(T_NUM,buf,l,c); t.u64=strtoull(buf,NULL,0); t.f64=(F64)t.u64; return t;
    }
    while(isdigit(peek())) buf[n++]=getc1();
    int isfloat=0;
    if(peek()=='.'){ isfloat=1; buf[n++]=getc1(); while(isdigit(peek())) buf[n++]=getc1(); }
    if(peek()=='e'||peek()=='E'){
      isfloat=1; buf[n++]=getc1(); if(peek()=='+'||peek()=='-') buf[n++]=getc1();
      while(isdigit(peek())) buf[n++]=getc1();
    }
    buf[n]=0; Token t=make(T_NUM,buf,l,c);
    if(isfloat){ t.f64=strtod(buf,NULL); }
    else { t.u64=strtoull(buf,NULL,10); t.f64=(F64)t.u64; }
    return t;
  }
  if(ch=='['){
    char buf[256]; int n=0;
    while(S.pos<S.len && S.data[S.pos]!=']' && n<255) buf[n++]=getc1();
    if(peek()==']') getc1();
    buf[n]=0; return make(K_INI_SEC,buf,l,c);
  }
  if(is_ident1(ch)){
    char buf[512]; int n=0; buf[n++]=ch; while(is_ident(peek())) buf[n++]=getc1(); buf[n]=0;
    struct { const char*k; Tok t; } kw[] = {
      {"U0",K_U0},{"deffunk",K_DEFFUNK},{"defunc",K_DEFUNC},{"end",K_END},
      {"return",K_RETURN},{"extern",K_EXTERN},
      {"if",K_IF},{"elif",K_ELIF},{"else",K_ELSE},{"while",K_WHILE},{"for",K_FOR},
      {"greaterthan",K_GT},{"lessthan",K_LT},{"ge",K_GE},{"le",K_LE},
      {"equals",K_EQ},{"notequals",K_NE},{"and",K_AND},{"or",K_OR},{"not",K_NOT},
      {"break",K_BREAK},{"continue",K_CONTINUE},
    };
    for(size_t i=0;i<sizeof(kw)/sizeof(kw[0]);++i) if(strcmp(buf,kw[i].k)==0) return make(kw[i].t,buf,l,c);
    return make(T_ID,buf,l,c);
  }
  if(strchr("+-*/%<>!&|^~[]{}", ch)){
    char buf[3]={ch,0,0}; if((ch=='<'||ch=='>'||ch=='='||ch=='!'||ch=='&'||ch=='|') && peek()=='='){ buf[1]=getc1(); }
    return make(T_ID,buf,l,c);
  }
  char unk[2]={ch,0}; return make(T_ID,unk,l,c);
}

/* ---------- Parser helpers ---------- */
static void need(Tok k){
  if(tk.kind!=k){
    fprintf(stderr,"%s:%d:%d: parse error (need %d, got %d)\n", g_input_name, tk.line, tk.col, k, tk.kind);
    exit(1);
  }
  if(tk.lex) { free(tk.lex); tk.lex=NULL; }
  tk=next();
}
static int accept(Tok k){ if(tk.kind==k){ if(tk.lex){ free(tk.lex); tk.lex=NULL; } tk=next(); return 1;} return 0; }
static const char* opword_to_c(Tok k){
  switch(k){
    case K_GT: return ">"; case K_LT: return "<";
    case K_GE: return ">="; case K_LE: return "<=";
    case K_EQ: return "=="; case K_NE: return "!=";
    case K_AND: return "&&"; case K_OR: return "||"; case K_NOT: return "!";
    default: return NULL;
  }
}

