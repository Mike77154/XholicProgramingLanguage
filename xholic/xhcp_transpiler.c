/* ---------- Emit expr token (with op-word mapping) ---------- */
static void emit_expr_token(Str*out){
  const char* sym = opword_to_c(tk.kind);
  if(sym){ sb_puts(out,sym); tk=next(); return; }
  if(tk.kind==T_STR){
    if(strcmp(tk.lex,"%%FORMAT_FROM_VAR%%")==0) { sb_puts(out,"/*FMT_FROM_VAR*/"); tk=next(); return; }
    sb_printf(out,"\"%s\"", tk.lex); tk=next(); return;
  }
  if(tk.kind==T_CHAR){
    if(!strcmp(tk.lex,"%%PUTCHAR_EXPR%%")){ sb_puts(out,"/*PUTCHAR_EXPR*/"); tk=next(); return; }
    sb_printf(out,"'%s'", tk.lex); tk=next(); return;
  }
  if(tk.lex){ sb_printf(out,"%s", tk.lex); tk=next(); return; }
}

/* ---------- Parse (...) generic with op-words ---------- */
static void parse_paren_condition(Str*out){
  need(T_LP);
  sb_puts(out,"(");
  int depth=1;
  while(depth>0 && tk.kind!=T_EOF){
    if(tk.kind==T_LP){ sb_puts(out,"("); tk=next(); depth++; continue; }
    if(tk.kind==T_RP){ sb_puts(out,")"); tk=next(); depth--; if(depth==0) break; else continue; }
    const char* sym=opword_to_c(tk.kind);
    if(sym){ sb_puts(out,sym); tk=next(); }
    else { if(tk.kind==T_STR){ if(strcmp(tk.lex,"%%FORMAT_FROM_VAR%%")==0) sb_puts(out,"/*FMT_FROM_VAR*/"); else sb_printf(out,"\"%s\"", tk.lex); tk=next(); }
           else if(tk.kind==T_CHAR){ if(!strcmp(tk.lex,"%%PUTCHAR_EXPR%%")) sb_puts(out,"/*PUTCHAR_EXPR*/"); else { sb_printf(out,"'%s'", tk.lex); } tk=next(); }
           else { if(tk.lex) sb_printf(out,"%s", tk.lex); tk=next(); } }
    sb_puts(out," ");
  }
}

/* ---------- INI header ---------- */
static void lower(char* s){ for(;*s;++s)*s=(char)tolower((unsigned char)*s); }

static void parse_header(Str*out){
  while(tk.kind==K_INI_SEC){
    char sec[128]; strncpy(sec, tk.lex, sizeof(sec)); sec[sizeof(sec)-1]=0;
    char sec_l[128]; strncpy(sec_l, sec, sizeof(sec_l)); lower(sec_l);
    tk=next();
    while(tk.kind==T_NEWLINE) tk=next();
    while(tk.kind!=T_EOF && tk.kind!=K_INI_SEC && tk.kind!=K_U0 && tk.kind!=K_DEFFUNK && tk.kind!=K_DEFUNC){
      if(tk.kind==T_NEWLINE){ tk=next(); continue; }
      if(!(tk.kind==T_ID && is_ident1(tk.lex[0]))) break;
      char key[256]; strncpy(key, tk.lex, sizeof(key)); tk=next();
      need(T_EQSIGN);
      if(!strcmp(sec_l,"defines")){
        if(tk.kind==T_NUM){ sb_printf(out,"const U64 %s = %lluULL;\n", key, (unsigned long long)tk.u64); tk=next(); }
        else if(tk.kind==T_STR && strcmp(tk.lex,"%%FORMAT_FROM_VAR%%")!=0){ sb_printf(out,"static const char %s[] = \"%s\";\n", key, tk.lex); tk=next(); }
        else if(tk.kind==T_ID){
          if(!strncmp(tk.lex,"0x",2)||!strncmp(tk.lex,"0X",2)){ U64 v=strtoull(tk.lex,NULL,16); sb_printf(out,"const U64 %s = 0x%llxULL;\n", key, (unsigned long long)v); tk=next(); }
          else if(!strcmp(tk.lex,"true")||!strcmp(tk.lex,"false")){ sb_printf(out,"const int %s = %d;\n", key, !strcmp(tk.lex,"true")); tk=next(); }
          else { sb_printf(out,"/* defines %s = %s (unhandled id) */\n", key, tk.lex); tk=next(); }
        } else { sb_printf(out,"/* defines %s (unsupported) */\n", key); }
      } else if(!strcmp(sec_l,"addresses")){
        if(tk.kind==T_ID && (!strncmp(tk.lex,"0x",2)||!strncmp(tk.lex,"0X",2))){
          U64 v=strtoull(tk.lex,NULL,16);
          sb_printf(out,"const U64 %s = 0x%llxULL;\n", key, (unsigned long long)v);
          tk=next();
        } else if(tk.kind==T_NUM){ sb_printf(out,"const U64 %s = %lluULL;\n", key, (unsigned long long)tk.u64); tk=next(); }
        else { sb_printf(out,"/* addresses %s unsupported */\n", key); }
      } else if(!strcmp(sec_l,"switches")){
        if(tk.kind==T_ID){
          char val[256]; strncpy(val, tk.lex, sizeof(val)); lower(val);
          if(!strcmp(key,"FREESTANDING") || !strcmp(key,"freestanding")){
            if(!strcmp(val,"on")||!strcmp(val,"true")||!strcmp(val,"1")) CFG_FREESTANDING=1; else CFG_FREESTANDING=0;
          }
          sb_printf(out,"/* switch %s=%s */\n", key, tk.lex); tk=next();
        } else if(tk.kind==T_NUM){ sb_printf(out,"/* switch %s=%llu */\n", key, (unsigned long long)tk.u64); tk=next(); }
        else if(tk.kind==T_STR){ sb_printf(out,"/* switch %s=\"%s\" */\n", key, tk.lex); tk=next(); }
      } else {
        sb_printf(out,"/* ini section [%s] key %s ignored */\n", sec, key);
      }
      while(tk.kind==T_NEWLINE) tk=next();
    }
    while(tk.kind==T_NEWLINE) tk=next();
  }
}

