static char* dupstr(const char*s){ return s?strdup(s):NULL; }
static void expect_param_ident(Token t){ if(!(t.kind==T_ID)) { fprintf(stderr,"%s:%d:%d: param expects ident\n", g_input_name, t.line, t.col); exit(1);} }
static const char* opword_to_c(Tok);

/* NUEVO: reconocer modificadores/qualifiers de tipo estilo C */
static int is_type_modifier(const char* s){
  return !strcmp(s,"const") || !strcmp(s,"volatile") || !strcmp(s,"restrict")
      || !strcmp(s,"unsigned") || !strcmp(s,"signed")
      || !strcmp(s,"short") || !strcmp(s,"long")
      || !strcmp(s,"_Atomic") || !strcmp(s,"_Alignas")
      || !strcmp(s,"*"); /* admitimos pegar asterisco como token ID */
}

static void parse_param_list(FuncSig*fs){
  int cap=8; fs->params=(Param*)calloc(cap,sizeof(Param)); fs->nparams=0; fs->ndefaults=0;
  while(tk.kind!=T_RP && tk.kind!=T_EOF){
    if(fs->nparams==cap){ cap*=2; fs->params=(Param*)realloc(fs->params,cap*sizeof(Param)); }
    Param *p=&fs->params[fs->nparams]; memset(p,0,sizeof(*p));
    if(!(tk.kind==T_ID)){ fprintf(stderr,"%s:%d:%d: expected type in param list\n", g_input_name, tk.line, tk.col); exit(1); }
    char typebuf[256]={0}; char namebuf[128]={0};

    /* 1er token del tipo */
    strncat(typebuf, tk.lex, sizeof(typebuf)-1); tk=next();

    /* NUEVO: aceptar calificador/compuesto/asteriscos repetidos */
    while (tk.kind==T_ID && is_type_modifier(tk.lex)) {
      strncat(typebuf," ", sizeof(typebuf)-1);
      strncat(typebuf, tk.lex, sizeof(typebuf)-1);
      tk=next();
    }

    expect_param_ident(tk); strncpy(namebuf, tk.lex, sizeof(namebuf)-1); tk=next();
    p->type_text = strdup(typebuf); p->name=strdup(namebuf); p->has_default=0; p->default_expr=NULL;

    if(accept(T_EQSIGN)){
      Str dex; sb_init(&dex);
      while(tk.kind!=T_COMMA && tk.kind!=T_RP && tk.kind!=T_EOF){
        const char* sym=opword_to_c(tk.kind);
        if(sym){ sb_puts(&dex,sym); tk=next(); }
        else {
          if(tk.kind==T_STR){
            if(strcmp(tk.lex,"%%FORMAT_FROM_VAR%%")==0) sb_puts(&dex,"/*FMT_FROM_VAR*/");
            else { sb_printf(&dex,"\"%s\"", tk.lex); }
            tk=next();
          } else if(tk.kind==T_CHAR){
            if(!strcmp(tk.lex,"%%PUTCHAR_EXPR%%")) sb_puts(&dex,"/*PUTCHAR_EXPR*/");
            else { sb_printf(&dex,"'%s'", tk.lex); }
            tk=next();
          } else {
            if(tk.lex) { sb_puts(&dex, tk.lex); tk=next(); }
          }
        }
        sb_puts(&dex," ");
      }
      p->has_default=1; p->default_expr = strdup(dex.buf); free(dex.buf);
    }
    fs->nparams++;
    if(tk.kind==T_COMMA){ tk=next(); continue; }
    else if(tk.kind==T_RP) break;
  }
}
static void emit_default_overloads(Str*out, const FuncSig*fs){
  int n=fs->nparams; int trailing=0; for(int i=n-1;i>=0;i--){ if(fs->params[i].has_default) trailing++; else break; }
  if(trailing==0) return;
  sb_printf(out, "/* default-arg overloads for %s */\n", fs->name);
  int total = fs->nparams;
  sb_printf(out, "#define XHCP_GET_%s(", fs->name);
  for(int i=1;i<=total;i++) sb_printf(out,"_%d,", i);
  sb_printf(out,"NAME,...) NAME\n");
  sb_printf(out, "#define %s(...) XHCP_GET_%s(", fs->name, fs->name);
  for(int i=1;i<=total;i++) sb_printf(out,"_%d,", i);
  sb_printf(out,"%s__impl,__VA_ARGS__)(__VA_ARGS__)\n", fs->name);
  int min_arity = total - trailing;
  for(int ar=min_arity; ar<total; ++ar){
    sb_printf(out, "static inline %s %s_%d(", fs->returns_value?(fs->ret_type?fs->ret_type:"int"):"U0", fs->name, ar);
    for(int i=0;i<ar;i++){ if(i) sb_puts(out,", "); sb_printf(out,"%s %s", fs->params[i].type_text, fs->params[i].name); }
    sb_puts(out, "){ return "); sb_printf(out, "%s__impl(", fs->name);
    for(int i=0;i<total;i++){ if(i) sb_puts(out,", "); if(i<ar) sb_printf(out,"%s", fs->params[i].name); else sb_printf(out,"%s", fs->params[i].default_expr?fs->params[i].default_expr:"0"); }
    sb_puts(out, "); }\n");
  }
  sb_puts(out,"\n");
}

/* ---------- Control blocks ---------- */
static void parse_if_chain(Str*out){
  need(K_IF);
  parse_paren_condition(out); need(T_COLON);
  sb_puts(out,"if "); sb_puts(out,"{\n");
  parse_block(out,1);
  sb_puts(out,"}");
  /* elif chain */
  while(tk.kind==K_ELIF){
    tk=next(); parse_paren_condition(out); need(T_COLON);
    sb_puts(out," else if "); sb_puts(out,"{\n");
    parse_block(out,1);
    sb_puts(out,"}");
  }
  /* "else if (...):" azúcar */
  if(tk.kind==K_ELSE){
    tk=next();
    if(tk.kind==K_IF){
      tk=next();
      parse_paren_condition(out); need(T_COLON);
      sb_puts(out," else if "); sb_puts(out,"{\n");
      parse_block(out,1);
      sb_puts(out,"}\n");
    } else {
      need(T_COLON);
      sb_puts(out," else {\n"); parse_block(out,1); sb_puts(out,"}");
    }
  }
  sb_puts(out,"\n");
}

static void parse_while(Str*out){
  need(K_WHILE);
  parse_paren_condition(out); need(T_COLON);
  sb_puts(out,"while "); sb_puts(out,"{\n");
  parse_block(out,1);
  sb_puts(out,"}\n");
}

static void parse_for(Str*out){
  need(K_FOR);
  need(T_LP);
  sb_puts(out,"for (");
  int depth=1;
  while(depth>0 && tk.kind!=T_EOF){
    if(tk.kind==T_LP){ sb_puts(out,"("); tk=next(); depth++; continue; }
    if(tk.kind==T_RP){ sb_puts(out,")"); tk=next(); depth--; if(depth==0) break; else continue; }
    const char* sym=opword_to_c(tk.kind);
    if(sym){ sb_puts(out,sym); tk=next(); }
    else { if(tk.kind==T_STR){ if(strcmp(tk.lex,"%%FORMAT_FROM_VAR%%")==0) sb_puts(out,"/*FMT_FROM_VAR*/"); else { sb_printf(out,"\"%s\"", tk.lex);} tk=next(); }
           else if(tk.kind==T_CHAR){ if(!strcmp(tk.lex,"%%PUTCHAR_EXPR%%")) sb_puts(out,"/*PUTCHAR_EXPR*/"); else { sb_printf(out,"'%s'", tk.lex);} tk=next(); }
           else { if(tk.lex) sb_printf(out,"%s", tk.lex); tk=next(); } }
    sb_puts(out," ");
  }
  need(T_COLON);
  sb_puts(out,") {\n");
  parse_block(out,1);
  sb_puts(out,"}\n");
}

static void parse_stmt(Str*out){
  if(tk.kind==K_IF){ parse_if_chain(out); return; }
  if(tk.kind==K_WHILE){ parse_while(out); return; }
  if(tk.kind==K_FOR){ parse_for(out); return; }
  if(tk.kind==K_BREAK){ tk=next(); sb_puts(out,"break;\n"); accept(T_SEMI); while(accept(T_NEWLINE)); return; }
  if(tk.kind==K_CONTINUE){ tk=next(); sb_puts(out,"continue;\n"); accept(T_SEMI); while(accept(T_NEWLINE)); return; }
  if(tk.kind==T_STR){
    if(strcmp(tk.lex,"%%FORMAT_FROM_VAR%%")==0){
      tk=next();
      sb_puts(out,"print(");
      emit_expr_token(out);
      while(accept(T_COMMA)){ sb_puts(out,", "); emit_expr_token(out); }
      sb_puts(out,");\n");
      accept(T_SEMI); while(accept(T_NEWLINE)); return;
    } else {
      /* string literal seguido de ,args => print(fmt,args...) */
      char* fmt = strdup(tk.lex);
      tk = next();
      if(tk.kind==T_COMMA){
        sb_puts(out,"print(\""); sb_puts(out, fmt); sb_puts(out,"\"");
        do { sb_puts(out,", "); tk=next(); emit_expr_token(out); } while(accept(T_COMMA));
        sb_puts(out,");\n");
      } else {
        sb_puts(out,"print(\""); sb_puts(out, fmt); sb_puts(out,"\");\n");
      }
      free(fmt);
      accept(T_SEMI); while(accept(T_NEWLINE)); return;
    }
  }

  if(tk.kind==K_RETURN){
    tk=next();
    sb_puts(out,"return");
    if(!(tk.kind==T_NEWLINE || tk.kind==T_SEMI)) sb_puts(out," ");
    while(tk.kind!=T_NEWLINE && tk.kind!=T_SEMI && tk.kind!=T_EOF){
      const char* sym=opword_to_c(tk.kind);
      if(sym){ sb_puts(out,sym); tk=next(); }
      else { if(tk.lex) sb_printf(out,"%s", tk.lex); tk=next(); }
    }
    if(!accept(T_SEMI)) sb_puts(out,";");
    while(accept(T_NEWLINE));
    sb_puts(out,"\n");
    return;
  }
  while(tk.kind!=T_NEWLINE && tk.kind!=T_SEMI && tk.kind!=T_EOF && tk.kind!=K_END && tk.kind!=K_ELIF && tk.kind!=K_ELSE){
    const char* sym=opword_to_c(tk.kind);
    if(sym){ sb_puts(out,sym); tk=next(); }
    else { if(tk.lex) sb_printf(out,"%s", tk.lex); tk=next(); }
    sb_puts(out," ");
  }
  accept(T_SEMI); accept(T_NEWLINE); sb_puts(out,";\n");
}

static void parse_block(Str*out,int allow_end){
  for(;;){
    while(accept(T_NEWLINE));
    if(allow_end && tk.kind==K_END){ tk=next(); break; }
    if(tk.kind==K_DEFFUNK || tk.kind==K_DEFUNC || tk.kind==K_U0 || tk.kind==T_EOF || tk.kind==K_ELIF || tk.kind==K_ELSE) break;
    parse_stmt(out);
  }
}

/* ---------- extern c / prototypes ---------- */
static void parse_extern(Str*out){
  need(K_EXTERN);
  int is_c_abi=0;
  if(tk.kind==T_STR && tk.lex && strcmp(tk.lex,"c")==0){ is_c_abi=1; tk=next(); }
  else if(tk.kind==T_ID && strcmp(tk.lex,"c")==0){ is_c_abi=1; tk=next(); }
  if(!(tk.kind==T_ID)){ fprintf(stderr,"%s:%d:%d: extern: expected return type\n", g_input_name, tk.line, tk.col); exit(1); }
  char rett[128]; strncpy(rett, tk.lex, sizeof(rett)); tk=next();
  if(!(tk.kind==T_ID)){ fprintf(stderr,"%s:%d:%d: extern: expected function name\n", g_input_name, tk.line, tk.col); exit(1); }
  char name[256]; strncpy(name, tk.lex, sizeof(name)); tk=next();
  need(T_LP);
  Str args; sb_init(&args);
  int first=1;
  while(tk.kind!=T_RP && tk.kind!=T_EOF){
    if(!first) sb_puts(&args,", ");
    if(tk.lex){ sb_puts(&args, tk.lex); tk=next(); }
    if(accept(T_COMMA)){ first=0; continue; }
    first=0;
  }
  need(T_RP);
  accept(T_SEMI); while(accept(T_NEWLINE));

  /* If extern c, collect ABI prototype for separate header */
  Str sig; sb_init(&sig);
  if(is_c_abi){
    /* Signature stored with ABI macros for the generated header */
    sb_printf(&sig, "XHCP_API %s XHCP_CALL %s(%s)", rett, name, args.buf);
    abi_push(sig.buf);
  }

  /* In the generated C unit, keep a normal extern declaration */
  sb_printf(out, "extern %s %s(%s);\n", rett, name, args.buf);

  free(args.buf);
  free(sig.buf);
}


/* ---------- toplevel ---------- */
static void parse_toplevel(Str*out){
  if(tk.kind==K_EXTERN){ parse_extern(out); return; }
  if(tk.kind==K_U0){
    tk=next();
    if(accept(T_COLON)){ sb_puts(out,"int main(void){\n"); parse_block(out,0); sb_puts(out,"return 0;}\n"); return; }
    else {
      if(tk.kind!=T_ID){ fprintf(stderr,"%s:%d:%d: expected name after U0\n", g_input_name, tk.line, tk.col); exit(1); }
      char fname[256]; strncpy(fname, tk.lex, sizeof(fname)); tk=next();
      need(T_LP);
      Str args; sb_init(&args);
      int first=1; while(tk.kind!=T_RP){ if(!first) sb_puts(&args,", "); if(tk.lex){ sb_puts(&args, tk.lex); tk=next(); } if(accept(T_COMMA)){ first=0; continue; } first=0; }
      need(T_RP); need(T_COLON);
      sb_printf(out,"U0 %s(%s){\n", fname, args.buf); free(args.buf);
      parse_block(out,0);
      sb_puts(out,"}\n"); return;
    }
  }
  if(tk.kind==K_DEFFUNK || tk.kind==K_DEFUNC){
    int is_defunc = (tk.kind==K_DEFUNC); tk=next(); need(T_DOT);
    if(tk.kind!=T_ID){ fprintf(stderr,"%s:%d:%d: expected Name after def*.\n", g_input_name, tk.line, tk.col); exit(1); }
    FuncSig fs; memset(&fs,0,sizeof(fs)); fs.name=strdup(tk.lex); fs.returns_value = is_defunc;
    tk=next(); need(T_LP);
    parse_param_list(&fs); need(T_RP);
    if(is_defunc){
      if(tk.kind==T_ID && strcmp(tk.lex,"->")==0){ tk=next(); if(!(tk.kind==T_ID)){ fprintf(stderr,"%s:%d:%d: need return type after ->\n", g_input_name, tk.line, tk.col); exit(1);} fs.ret_type=strdup(tk.lex); tk=next(); }
      else { fs.ret_type=strdup("int"); }
    }
    need(T_COLON);
    emit_default_overloads(out,&fs);
    sb_printf(out,"%s %s__impl(", is_defunc?(fs.ret_type?fs.ret_type:"int"):"U0", fs.name);
    for(int i=0;i<fs.nparams;i++){ if(i) sb_puts(out,", "); sb_printf(out,"%s %s", fs.params[i].type_text, fs.params[i].name); }
    sb_puts(out,"){\n");
    parse_block(out,0);
    sb_puts(out,"}\n");
    if(fs.ndefaults==0){ sb_printf(out,"#ifndef %s\n#define %s(...) %s__impl(__VA_ARGS__)\n#endif\n", fs.name, fs.name, fs.name); }
    for(int i=0;i<fs.nparams;i++){ free(fs.params[i].type_text); free(fs.params[i].name); if(fs.params[i].default_expr) free(fs.params[i].default_expr); }
    free(fs.params); free(fs.name); if(fs.ret_type) free(fs.ret_type);
    return;
  }
  if(tk.kind==T_NEWLINE){ tk=next(); return; }
  sb_puts(out,"int main(void){\n"); parse_block(out,0); sb_puts(out,"return 0;}\n");
}

/* ---------- prelude emission ---------- */
static void emit_prelude(Str*out){
  if(CLI_FREESTANDING!=-1) CFG_FREESTANDING = CLI_FREESTANDING;
  sb_printf(out, "#line 1 \"%s\"\n", g_input_name);
  if(!CFG_FREESTANDING){
    sb_puts(out, "#include \"xhcp_rt.h\"\n");
  } else {
    sb_puts(out,
      "#include <stdint.h>\n"
      "typedef signed char I8; typedef unsigned char U8; typedef short I16; typedef unsigned short U16;\n"
      "typedef int I32; typedef unsigned int U32; typedef long long I64; typedef unsigned long long U64; typedef double F64; typedef void U0;\n"
      "__attribute__((weak)) void xhcp_hw_putc(int c){ (void)c; }\n"
      "__attribute__((weak)) void xhcp_hw_write(const char* s, unsigned long n){ (void)s; (void)n; }\n"
      "static void xhcp_putc(int c){ xhcp_hw_putc(c); }\n"
      "static void xhcp_print(const char*fmt, ...){ (void)fmt; }\n"
      "#define MMIO8(a)  (*(volatile U8*)(a))\n#define MMIO16(a) (*(volatile U16*)(a))\n#define MMIO32(a) (*(volatile U32*)(a))\n#define MMIO64(a) (*(volatile U64*)(a))\n"
      "#if defined(__x86_64__)||defined(__i386__)\n"
      "static inline void outb(U16 port, U8 val){ __asm__ volatile (\"outb %0,%1\"::\"a\"(val),\"Nd\"(port)); }\n"
      "static inline U8 inb(U16 port){ U8 ret; __asm__ volatile (\"inb %1,%0\":\"=a\"(ret):\"Nd\"(port)); return ret; }\n"
      "#endif\n"
    );
  }
}

static void parse_file(Str*out){
  Str header; sb_init(&header);
  parse_header(&header);
  emit_prelude(out);
  sb_puts(out, header.buf);
  free(header.buf);
  while(tk.kind!=T_EOF) parse_toplevel(out);
}

/* ---------- Token dump (opcional) ---------- */
static void dump_all_tokens(const char* in){
  size_t n; char *buf=read_all(in,&n);
  S.data=buf; S.len=n; S.pos=0; S.line=1; S.col=1;
  Token t; do{ t=next(); fprintf(stderr,"[%d:%d] kind=%d lex=%s\n", t.line,t.col, t.kind, t.lex?t.lex:"(nil)"); if(t.lex) free(t.lex); }while(t.kind!=T_EOF);
  free(buf);
}

/* ---------- main ---------- */
int main(int argc,char**argv){
  if(argc<2){ fprintf(stderr,"usage: %s input.xhcp [--freestanding|--host] [-o out.c] [--dump-tokens] [--emit-abi <abi.h>] > out.c\n", argv[0]); return 1; }
  const char* in = NULL;
  for(int i=1;i<argc;i++){
    if(strcmp(argv[i],"--freestanding")==0) CLI_FREESTANDING=1;
    else if(strcmp(argv[i],"--host")==0) CLI_FREESTANDING=0;
    else if(strcmp(argv[i],"--dump-tokens")==0) g_dump_tokens=1;
    else if(strcmp(argv[i],"--emit-abi")==0 && i+1<argc){ g_emit_abi_path = argv[++i]; }
    else if(strcmp(argv[i],"-o")==0 && i+1<argc){ g_output_name = argv[++i]; }
    else in = argv[i];
  }
  if(!in){ fprintf(stderr,"missing input\n"); return 1; }
  g_input_name = in;

  if(g_dump_tokens){ dump_all_tokens(in); }

  size_t n; char *buf=read_all(in, &n);
  S.data=buf; S.len=n; S.pos=0; S.line=1; S.col=1;
  tk=next();
  Str out; sb_init(&out);
  parse_file(&out);

  FILE* fo = stdout;
  if(g_output_name){
    fo = fopen(g_output_name,"wb");
    if(!fo){ perror("fopen -o"); free(out.buf); free(buf); return 1; }
  }
  fwrite(out.buf,1,out.n,fo);
  if(fo!=stdout) fclose(fo);
  free(out.buf); free(buf);
  if(g_emit_abi_path){ abi_write_header(g_emit_abi_path); }
  return 0;
}
