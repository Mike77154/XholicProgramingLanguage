typedef struct { char *sig; } AbiItem;
typedef struct { AbiItem* v; int n, cap; } AbiVec;
static AbiVec g_abi;

/* ABI defaults for generated headers (portable) */
#define XHCP_ABI_VERSION_DEFAULT "0x00010000"

static void abi_push(const char* sig){
  if(!sig) return;
  if(g_abi.n==g_abi.cap){
    int nc = g_abi.cap? g_abi.cap*2 : 16;
    AbiItem* nv = (AbiItem*)realloc(g_abi.v, nc*sizeof(AbiItem));
    if(!nv){ perror("realloc abi"); exit(1); }
    g_abi.v=nv; g_abi.cap=nc;
  }
  g_abi.v[g_abi.n++].sig = strdup(sig);
}

static void abi_write_header(const char* path){
  if(!path) return;
  FILE* fo = fopen(path, "wb");
  if(!fo){ perror("fopen --emit-abi"); return; }
  fprintf(fo, "/* Auto-generated by xhcp_transpiler --emit-abi */\n");
  fprintf(fo, "#ifndef XHCP_ABI_H\n#define XHCP_ABI_H\n\n");

  /* extern "C" guards */
  fprintf(fo, "#ifdef __cplusplus\nextern \"C\" {\n#endif\n\n");

  /* includes + ABI macros */
  fprintf(fo, "#include <stdint.h>\n#include <stddef.h>\n\n");
  fprintf(fo,
    "/* ===== Stable ABI versioning (MAJOR<<16 | MINOR<<8 | PATCH) ===== */\n"
    "#ifndef XHCP_ABI_VERSION\n#define XHCP_ABI_VERSION %s\n#endif\n\n"
    "/* ===== Export / Calling convention macros (platform-portable) ===== */\n"
    "#if defined(_WIN32) || defined(_WIN64)\n"
    "  #ifndef XHCP_API\n"
    "    #define XHCP_API __declspec(dllimport)\n"
    "  #endif\n"
    "  #ifndef XHCP_CALL\n"
    "    #define XHCP_CALL __cdecl\n"
    "  #endif\n"
    "#else\n"
    "  #ifndef XHCP_API\n"
    "    #define XHCP_API\n"
    "  #endif\n"
    "  #ifndef XHCP_CALL\n"
    "    #define XHCP_CALL\n"
    "  #endif\n"
    "#endif\n\n",
    XHCP_ABI_VERSION_DEFAULT
  );

  /* emit prototypes (already have full signature lines) */
  for(int i=0;i<g_abi.n;i++){
    fprintf(fo, "%s;\n", g_abi.v[i].sig);
  }
  fprintf(fo, "\n#ifdef __cplusplus\n}\n#endif\n\n");
  fprintf(fo, "#endif /* XHCP_ABI_H */\n");
  fclose(fo);
}


